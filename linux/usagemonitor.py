# agy keeps its Google sign-in in the system keyring (go-keyring: service "gemini", user "antigravity"),
# as JSON {"token": {"access_token", "expiry", ...}, "id_token_email"}. The token is only read, never
# refreshed: agy refreshes it (about every hour) while it runs.
AGY_SERVICE, AGY_USER = "gemini", "antigravity"
CLOUD_CODE = "https://cloudcode-pa.googleapis.com/v1internal:"
# The quota endpoints answer 403 to unknown clients, so the requests identify themselves as agy
ANTIGRAVITY_USER_AGENT = "antigravity"
_agy_cache = {}  # account -> (project, plan) from loadCodeAssist


def agy_installed():
    return (os.path.isdir(os.path.join(HOME, ".gemini", "antigravity-cli"))
            or shutil.which("agy") is not None)


def read_agy_credential():
    """Secret Service via secret-tool (Linux); returns the JSON text or None."""
    try:
        out = subprocess.run(["secret-tool", "lookup", "service", AGY_SERVICE, "username", AGY_USER],
                             capture_output=True, timeout=10)
    except (OSError, subprocess.SubprocessError):
        return None
    text = out.stdout.decode("utf-8", "replace").strip()
    if text.startswith("go-keyring-base64:"):
        import base64
        text = base64.b64decode(text[len("go-keyring-base64:"):]).decode("utf-8", "replace")
    return text or None


def window_label(window, display_name):
    return {"weekly": T("7 hari", "7 days"), "daily": T("1 hari", "1 day"), "hourly": T("1 jam", "1 hour"),
            "five_hour": T("5 jam", "5 hours"), "5h": T("5 jam", "5 hours")}.get(
        (window or "").lower(), window or display_name or "Limit")


def short_group_name(name):
    """'Claude and GPT models' -> 'Claude & GPT'"""
    if not name:
        return None
    if name.lower().endswith(" models"):
        name = name[:-7]
    return name.replace(" and ", " & ")


def fetch_antigravity():
    s = ProviderStatus("Antigravity")
    s.fixed_rows = False
    try:
        raw = read_agy_credential()
        if not raw:
            if not shutil.which("secret-tool"):
                s.error = T("Butuh 'secret-tool' (paket libsecret-tools) untuk membaca login agy.",
                            "Needs 'secret-tool' (libsecret-tools package) to read the agy sign-in.")
            else:
                s.error = T("Belum login. Jalankan 'agy' lalu login dengan akun Google.", "Not logged in. Run 'agy' and sign in with Google.")
            return s
        cred = json.loads(raw)
        tok = cred.get("token") or {}
        token = tok.get("access_token")
        s.account = cred.get("id_token_email")
        if not token:
            s.error = T("Token tidak ditemukan. Login ulang lewat 'agy'.", "Token not found. Sign in again with 'agy'.")
            return s
        exp = parse_iso(tok.get("expiry"))
        if exp and exp < datetime.now(timezone.utc):
            s.error = T("Token kedaluwarsa. Jalankan 'agy' agar token di-refresh.", "Token expired. Run 'agy' to refresh it.")
            s.keep_previous = True
            return s
        h = {"Authorization": "Bearer " + token, "User-Agent": ANTIGRAVITY_USER_AGENT}
        if s.account not in _agy_cache:
            lca = http_get(CLOUD_CODE + "loadCodeAssist", h,
                           {"metadata": {"ideType": "ANTIGRAVITY", "platform": "PLATFORM_UNSPECIFIED", "pluginType": "GEMINI"}})
            plan = (lca.get("paidTier") or {}).get("name") or (lca.get("currentTier") or {}).get("name")
            _agy_cache[s.account] = (lca.get("cloudaicompanionProject") or "", plan)
        project, s.plan = _agy_cache[s.account]
        root = http_get(CLOUD_CODE + "retrieveUserQuotaSummary", h, {"project": project})
        for gr in root.get("groups") or []:
            group = short_group_name(gr.get("displayName"))
            for b in gr.get("buckets") or []:
                if b.get("disabled"):
                    continue
                win = window_label(b.get("window"), b.get("displayName"))
                w = UsageWindow(win + " · " + group if group else win)
                frac, amount = num(b.get("remainingFraction")), num(b.get("remainingAmount"))
                if frac is not None:
                    w.percent = max(0.0, min(100.0, (1 - frac) * 100))
                elif amount is not None:
                    w.label += T(" (sisa %d)", " (%d left)") % amount
                w.reset_at = parse_iso(b.get("resetTime"))
                s.more_rows.append(w)
        if not s.more_rows:
            s.infos.append(T("Tidak ada batas kuota untuk akun ini.", "No quota limits reported for this account."))
    except HttpError as e:
        _agy_cache.clear()
        s.rate_limited = e.code == 429
        s.keep_previous = e.code == 401
        s.error = (T("Dibatasi server (429). Dicoba lagi otomatis.", "Rate limited by the server (429). Retrying automatically.")
                   if e.code == 429 else
                   T("Token ditolak (%d). Jalankan 'agy' agar token di-refresh.", "Token rejected (%d). Run 'agy' to refresh it.") % e.code
                   if e.code in (401, 403) else "HTTP %d: %s" % (e.code, e))
    except Exception as e:
        s.error = str(e)
    return s


