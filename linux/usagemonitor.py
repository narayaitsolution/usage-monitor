        self.busy = True
        box = self.new_box()
        self.text(box, T("Memeriksa versi…", "Checking versions…"), size="large", bold=True)
        self.text(box, T("Versi Anda: %s. Mengecek versi terbaru di GitHub…",
                         "You have version %s. Checking the latest version on GitHub…") % VERSION, dim=True)
        self.present()

        def done(rel, err):
            self.busy = False
            if err:
                self.show_offer(T("Gagal memeriksa versi di GitHub: %s", "Could not check the version on GitHub: %s") % err)
            elif not is_newer(rel):
                self.show_up_to_date(rel)
            elif compare_versions(rel.version, self.rel.version) != 0:
                # GitHub now has a different release than the one offered: show its notes first
                self.rel = rel
                self.show_offer(None)
            else:
                self.rel = rel
                self.start_download()
        self.run_async(fetch_latest, done)

