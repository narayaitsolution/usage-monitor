class ProviderStatus:
    def __init__(self, name):
        self.name = name
        self.plan = None
        self.account = None
        self.error = None
        self.five = UsageWindow(T("5 jam", "5 hours"))
        self.week = UsageWindow(T("7 hari", "7 days"))
        self.more_rows = []        # extra limits, e.g. Claude's weekly limit for one model
        self.infos = []            # extra lines: Claude "Limit resets", ChatGPT "usage limit reset" credits
        self.fixed_rows = True     # False for providers without the 5h/7d pair (Antigravity)
        self.keep_previous = False # soft error (expired token): keep showing the last good data
        self.rate_limited = False  # server answered HTTP 429
        self.note = None           # shown under the rows, e.g. when displaying older data
        self.fetched_at = None

    def rows(self):
        return ([self.five, self.week] if self.fixed_rows else []) + self.more_rows

    def icon_values(self):
        """Bars in the tray icon: 5h & 7d, or the first two limits (Antigravity: one per model group)."""
        if self.fixed_rows:
            return [self.five.percent, self.week.percent]
        return [w.percent for w in self.more_rows[:2]] or [None]


def parse_iso(s):
    try:
        return datetime.fromisoformat(s.replace("Z", "+00:00")) if s else None
    except ValueError:
        return None


class HttpError(Exception):
    def __init__(self, code, msg):
        super().__init__(msg)
        self.code = code


def http_get(url, headers, body=None):
    """GET, or POST with a JSON body when body is given."""
    h = {"Accept": "application/json", "User-Agent": USER_AGENT}
    h.update(headers)
    data = None
    if body is not None:
        data = json.dumps(body).encode("utf-8")
        h["Content-Type"] = "application/json"
    req = urllib.request.Request(url, data=data, headers=h)
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        body = ""
        try:
            body = e.read().decode("utf-8", "replace")[:120]
        except Exception:
            pass
        raise HttpError(e.code, body or e.reason)
    except urllib.error.URLError as e:
        raise Exception(T("Koneksi gagal: %s", "Connection failed: %s") % e.reason)


def read_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def num(v):
    try:
        return float(v) if v is not None else None
    except (TypeError, ValueError):
        return None


