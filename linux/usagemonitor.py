def write_icon(path, statuses, size=22):
    """Two bars (5h, 7d) per shown provider, stacked in menu order."""
    px = [[(0, 0, 0, 0)] * size for _ in range(size)]
    groups = [st.icon_values() if st is not None and st.error is None else [None, None] for st in statuses]
    n = max(1, len(groups))
    bars = max(1, sum(len(g) for g in groups))
    gap, group_gap = 1, (3 if bars <= 4 else 2)
    fixed = (bars - n) * gap + (n - 1) * group_gap
    bar_h = max(1, min(9, (size - fixed) // bars))
    y = max(0, (size - (bars * bar_h + fixed)) // 2)
    for st, values in zip(statuses, groups):
        for pct in values:
            err = st is not None and st.error is not None
            track = (150, 60, 60, 200) if err else (128, 128, 128, 150)
            fill = 0
            if pct is not None:
                fill = int(round(size * max(0, min(100, pct)) / 100.0))
                if pct > 0 and fill < 1:
                    fill = 1
            color = level_color(pct) + (255,) if pct is not None else None
            for yy in range(y, min(size, y + bar_h)):
                for xx in range(size):
                    px[yy][xx] = color if xx < fill else track
            y += bar_h + gap
        y += group_gap - gap

    raw = b"".join(b"\x00" + bytes(c for p in row for c in p) for row in px)

    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)

    data = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
    with open(path, "wb") as f:
        f.write(data)


