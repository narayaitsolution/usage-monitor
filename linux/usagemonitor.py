class TrayApp:
    def __init__(self):
        self.Gtk, self.GLib, AppIndicator = load_gui()
        self.data = {}           # provider id -> ProviderStatus
        self.hidden = load_hidden()
        self.installed = installed_providers()
        self.updated = None
        self.busy = False
        self.pending = False
        self.alerted = {}
        self.next_allowed = {}   # provider id -> datetime; back-off after HTTP 429
        self.backoff_min = {}
        self.icon_dir = os.path.join(os.environ.get("XDG_CACHE_HOME") or os.path.join(HOME, ".cache"), APP_ID)
        os.makedirs(self.icon_dir, exist_ok=True)
        for f in os.listdir(self.icon_dir):
            if f.endswith(".png"):
                try:
                    os.remove(os.path.join(self.icon_dir, f))
                except OSError:
                    pass
        self.icon_path = None
        self.about_win = None
        self.update_win = None
        self.donors_win = None

        self.ind = AppIndicator.Indicator.new(APP_ID, "", AppIndicator.IndicatorCategory.APPLICATION_STATUS)
        self.ind.set_status(AppIndicator.IndicatorStatus.ACTIVE)
        self.ind.set_title(APP_NAME)
        self.update_icon()
        self.rebuild_menu()

        self.GLib.timeout_add_seconds(REFRESH_SECONDS, self._tick)
        # keep "reset dalam" countdown fresh and pick up newly installed CLIs
        self.GLib.timeout_add_seconds(30, self._rebuild_tick)
        self.refresh()
        # check GitHub for a newer version shortly after start up
        self.GLib.timeout_add_seconds(4, self._startup_update_check)

    # ------------------------------------------------------------ update & about
    def _startup_update_check(self):
        def work():
            try:
                rel = fetch_latest()
            except Exception:
                return  # offline or GitHub unavailable: try again next start
            if is_newer(rel) and not is_skipped(rel):
                self.GLib.idle_add(lambda: self.show_update(rel) and False)
        threading.Thread(target=work, daemon=True).start()
        return False

    def show_update(self, rel):
        w = self.update_win
        if w and not w.closed:
            if compare_versions(w.rel.version, rel.version) == 0:
                w.present()
                return
            w.close()
        self.update_win = UpdateWindow(self, rel)

    def show_about(self, *_):
        if self.about_win and not self.about_win.closed:
            self.about_win.present()
            return
        self.about_win = AboutWindow(self)

    def show_donors(self, *_):
        if self.donors_win and not self.donors_win.closed:
            self.donors_win.present()
            return
        self.donors_win = DonorsWindow(self)

    def set_language(self, item, code):
        if not item.get_active() or lang_choice() == code:
            return
        was_id = is_id()
        set_lang_choice(code)
        if is_id() != was_id:
            # reopen windows in the new language; texts from the last fetch are redone by a refresh
            for attr in ("about_win", "donors_win"):
                w = getattr(self, attr)
                if w and not w.closed:
                    w.close()
                    setattr(self, attr, None)
            u = self.update_win
            if u and not u.closed and not u.busy:
                u.close()
                self.update_win = UpdateWindow(self, u.rel)
            for st in self.data.values():
                st.note = None
            self.refresh()
        self.GLib.idle_add(self.rebuild_menu)

    def shown(self):
        """Installed providers that are ticked. Never empty."""
        lst = [p for p in self.installed if p.id not in self.hidden]
        return lst or self.installed[:1]

    def _tick(self):
        self.refresh()
        return True

    def _rebuild_tick(self):
        before = [p.id for p in self.installed]
        self.installed = installed_providers()
        if [p.id for p in self.installed] != before:
            self.update_icon()
            if any(p.id not in self.data for p in self.shown()):
                self.refresh()
        self.rebuild_menu()
        return True

    def toggle_provider(self, item, prov):
        on = item.get_active()
        shown = self.shown()
        if not on and prov in shown and len(shown) == 1:
            # at least one provider must stay ticked
            self.GLib.idle_add(self.rebuild_menu)
            return
        if on:
            self.hidden.discard(prov.id)
        else:
            self.hidden.add(prov.id)
        save_hidden(self.hidden)
        self.update_icon()
        self.GLib.idle_add(self.rebuild_menu)
        if on and prov.id not in self.data and self.can_fetch(prov):
            self.refresh()

    def can_fetch(self, prov):
        t = self.next_allowed.get(prov.id)
        return t is None or datetime.now() >= t

    def store(self, prov, r):
        prev = self.data.get(prov.id)
        if r.rate_limited:
            # back-off: 5, 10, 20, then max 30 minutes
            mins = 5 if not self.backoff_min.get(prov.id) else min(30, self.backoff_min[prov.id] * 2)
            self.backoff_min[prov.id] = mins
            retry = datetime.now() + timedelta(minutes=mins)
            self.next_allowed[prov.id] = retry
            if prev is not None and prev.error is None:
                prev.note = T("Dibatasi server (429) · data %s · coba lagi %s", "Rate limited (429) · data %s · retry %s") % (
                    prev.fetched_at.strftime("%H:%M"), retry.strftime("%H:%M"))
                return  # keep showing the last good data
            r.error = T("Dibatasi server (429). Dicoba lagi %s.", "Rate limited by the server (429). Retrying at %s.") % retry.strftime("%H:%M")
        elif r.keep_previous and prev is not None and prev.error is None:
            prev.note = T("%s · data %s", "%s · data from %s") % (r.error, prev.fetched_at.strftime("%H:%M"))
            return  # soft error (expired token): keep showing the last good data
        else:
            self.backoff_min.pop(prov.id, None)
            self.next_allowed.pop(prov.id, None)
            r.fetched_at = datetime.now()
        self.data[prov.id] = r

    def refresh(self, *_):
        if self.busy:
            self.pending = True
            return
        provs = [p for p in self.shown() if self.can_fetch(p)]
        if not provs:  # everything is backing off
            self.rebuild_menu()
            return
        self.busy = True
        self.pending = False
        self.rebuild_menu()

        def work():
            res = {}
            threads = [threading.Thread(target=lambda p=p: res.__setitem__(p.id, p.fetch())) for p in provs]
            for t in threads:
                t.start()
            for t in threads:
                t.join()
            self.GLib.idle_add(self.apply, res, provs)

        threading.Thread(target=work, daemon=True).start()

    def apply(self, res, provs):
        for p in provs:
            if p.id in res:
                self.store(p, res[p.id])
        self.updated = datetime.now()
        self.busy = False
        self.update_icon()
        self.rebuild_menu()
        for p in provs:
            st = self.data.get(p.id)
            if st and st.error is None:
                for i, w in enumerate(st.rows()):
                    self.check_alert(p, i, w)
        if self.pending:
            self.refresh()
        return False

    def check_alert(self, prov, index, w):
        # keyed by row position, not label, so switching the language doesn't repeat an alert
        key = "%s#%d" % (prov.id, index)
        label = w.label
        high = w.percent is not None and w.percent >= 90
        if high and not self.alerted.get(key) and shutil.which("notify-send"):
            subprocess.Popen(["notify-send", "-a", APP_NAME, "-u", "critical",
                              T("Usage %s tinggi", "%s usage is high") % prov.title,
                              T("%s %s: %s terpakai. %s", "%s %s: %s used. %s")
                              % (prov.title, label, pct_text(w.percent), reset_text(w.reset_at))])
        self.alerted[key] = high

    def update_icon(self):
        path = os.path.join(self.icon_dir, "icon-%d.png" % int(time.time() * 1000))
        write_icon(path, [self.data.get(p.id) for p in self.shown()])
        self.ind.set_icon_full(path, APP_NAME)
        if self.icon_path and os.path.exists(self.icon_path):
            try:
                os.remove(self.icon_path)
            except OSError:
                pass
        self.icon_path = path

    def rebuild_menu(self):
        Gtk = self.Gtk
        menu = Gtk.Menu()

        def label(text):
            item = Gtk.MenuItem(label=text)
            menu.append(item)
            return item

        shown = self.shown()
        for prov in shown:
            st = self.data.get(prov.id)
            head = prov.title
            if st and st.plan:
                head += "  [%s]" % st.plan.upper()
            if st and st.account:
                head += "  —  " + st.account
            label(head)
            if st is None:
                label("    " + (T("Memuat…", "Loading…") if self.busy else T("Belum ada data", "No data yet")))
            elif st.error:
                label("    ⚠ " + st.error)
            else:
                # one compact line per limit: 🟢 5 jam  ▰▰▱▱▱▱▱▱  40%   ↻ 26m · 09:40
                for w in st.rows():
                    label("  %s %s  %s  %s   %s" % (level_dot(w.percent), w.label, text_bar(w.percent, 8),
                                                    pct_text(w.percent), short_reset(w.reset_at)))
                for info in st.infos:
                    label("  " + info)
                if st.note:
                    label("    ⚠ " + st.note)
            menu.append(Gtk.SeparatorMenuItem())

        if self.busy:
            foot = T("Memuat…", "Loading…")
        elif self.updated:
            foot = T("Diperbarui %s  ·  tiap 5 menit", "Updated %s  ·  every 5 minutes") % self.updated.strftime("%H:%M:%S")
        else:
            foot = T("Belum ada data", "No data yet")
        label(foot).set_sensitive(False)

        label(T("↻ Refresh sekarang", "↻ Refresh now")).connect("activate", self.refresh)
        menu.append(Gtk.SeparatorMenuItem())

        # Provider selection: only CLIs installed on this computer are listed
        label(T("Tampilkan akun:", "Show accounts:")).set_sensitive(False)
        for prov in self.installed:
            item = Gtk.CheckMenuItem(label=prov.menu_title)
            item.set_active(prov in shown)
            item.connect("toggled", self.toggle_provider, prov)
            menu.append(item)
        menu.append(Gtk.SeparatorMenuItem())

        auto = Gtk.CheckMenuItem(label=T("Jalankan saat login", "Run at login"))
        auto.set_active(autostart_enabled())
        auto.connect("toggled", lambda i: set_autostart(i.get_active()))
        menu.append(auto)

        # Language: follow the system, or a fixed language
        lang_item = Gtk.MenuItem(label="⚙ " + T("Bahasa", "Language"))
        sub = Gtk.Menu()
        group = None
        system_name = "Bahasa Indonesia" if system_is_indonesian() else "English"
        for code, name in (("", T("Ikuti sistem", "Follow system") + " (%s)" % system_name),
                           ("id", "Bahasa Indonesia"), ("en", "English")):
            r = Gtk.RadioMenuItem.new_with_label_from_widget(group, name)
            group = group or r
            r.set_active(lang_choice() == code)
            r.connect("toggled", self.set_language, code)
            sub.append(r)
        lang_item.set_submenu(sub)
        menu.append(lang_item)
        menu.append(Gtk.SeparatorMenuItem())

        label(T("♥ Donatur & donasi…", "♥ Donors & donate…")).connect("activate", self.show_donors)
        label(T("ⓘ Tentang & update…", "ⓘ About & update…")).connect("activate", self.show_about)
        menu.append(Gtk.SeparatorMenuItem())
        label(T("Keluar", "Exit")).connect("activate", self.quit)

        menu.show_all()
        self.ind.set_menu(menu)
        self.menu = menu  # keep reference
        return False

    def quit(self, *_):
        for w in (self.about_win, self.update_win, self.donors_win):
            if w:
                w.close()
        if self.icon_path and os.path.exists(self.icon_path):
            try:
                os.remove(self.icon_path)
            except OSError:
                pass
        self.Gtk.main_quit()

    def run(self):
        self.Gtk.main()


