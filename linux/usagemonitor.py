def _asset_score(name):
    n = name.lower()
    if "win" in n.replace("darwin", "") or "mac" in n or "darwin" in n or n.endswith(".exe"):
        return 0
    if n.endswith(".py"):
        return 3 if "usagemonitor" in re.sub(r"[^a-z0-9.]", "", n) else 2
    if "linux" in n:
        return 1
    return 0


def fetch_latest():
    """Latest published release on GitHub (drafts and pre-releases are ignored by the API)."""
    try:
        root = http_get("https://api.github.com/repos/%s/releases/latest" % REPO, {})
    except HttpError as e:
        if e.code == 404:
            raise Exception(T("Belum ada rilis di GitHub.", "No release on GitHub yet."))
        if e.code in (403, 429):
            raise Exception(T("GitHub membatasi permintaan. Coba lagi nanti.", "GitHub is rate limiting requests. Try again later."))
        raise Exception(T("GitHub membalas HTTP %d.", "GitHub answered HTTP %d.") % e.code)
    r = ReleaseInfo()
    r.tag = root.get("tag_name") or ""
    r.version = normalize_version(r.tag) or normalize_version(root.get("name") or "")
    if not r.version:
        raise Exception(T("Tag rilis tidak berisi nomor versi: ", "Release tag has no version number: ") + r.tag)
    r.notes = (root.get("body") or "").strip()
    r.page_url = root.get("html_url") or r.page_url
    best = 0
    for a in root.get("assets") or []:
        score = _asset_score(a.get("name") or "")
        if score > best and a.get("browser_download_url"):
            best = score
            r.asset_name = a["name"]
            r.asset_url = a["browser_download_url"]
            r.asset_size = int(a.get("size") or 0)
    if not r.asset_url and root.get("zipball_url"):
        r.asset_name = "usage-monitor-%s-source.zip" % r.version
        r.asset_url = root["zipball_url"]
        r.is_source = True
    return r


def downloads_dir():
    try:
        d = subprocess.run(["xdg-user-dir", "DOWNLOAD"], capture_output=True, text=True, timeout=5).stdout.strip()
        if d and d != HOME and os.path.isdir(d):
            return d
    except Exception:
        pass
    return os.path.join(HOME, "Downloads")


def unique_path(folder, name):
    """'usagemonitor.py' -> 'usagemonitor (1).py' when the name is taken, like a browser does."""
    stem, ext = os.path.splitext(name)
    path = os.path.join(folder, name)
    i = 1
    while os.path.exists(path) or os.path.exists(path + ".part"):
        path = os.path.join(folder, "%s (%d)%s" % (stem, i, ext))
        i += 1
    return path


def download_release(rel, progress=None):
    """Downloads the release file into the Downloads folder. progress gets 0-100, or -1 if the size is unknown."""
    folder = downloads_dir()
    os.makedirs(folder, exist_ok=True)
    path = unique_path(folder, os.path.basename(rel.asset_name))
    tmp = path + ".part"
    req = urllib.request.Request(rel.asset_url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=60) as resp, open(tmp, "wb") as f:
            total = int(resp.headers.get("Content-Length") or 0) or rel.asset_size
            done, last = 0, None
            while True:
                chunk = resp.read(65536)
                if not chunk:
                    break
                f.write(chunk)
                done += len(chunk)
                pct = min(100, done * 100 // total) if total else -1
                if progress and pct != last:
                    last = pct
                    progress(pct)
        os.replace(tmp, path)
        return path
    except Exception as e:
        try:
            os.remove(tmp)
        except OSError:
            pass
        if isinstance(e, urllib.error.URLError):
            raise Exception(T("Unduhan gagal: %s", "Download failed: %s") % getattr(e, "reason", e))
        raise


class DonorList:
    def __init__(self):
        self.donate_url = DONATE_URL
        self.donors = []   # dicts with "name" and optional "note", "date"


def fetch_donors():
    """donors.json from the repository:
    { "donate_url": "https://...", "donors": [ { "name": "Budi", "note": "Semangat!", "date": "2026-11-19" } ] }"""
    lst = DonorList()
    try:
        root = http_get(DONORS_URL + "?t=%d" % int(time.time()), {})
    except HttpError as e:
        if e.code == 404:
            return lst  # file not published yet
        raise Exception(T("GitHub membalas HTTP %d.", "GitHub answered HTTP %d.") % e.code)
    url = root.get("donate_url") if isinstance(root, dict) else None
    if isinstance(url, str) and url.startswith(("https://", "http://")):
        lst.donate_url = url
    for d in (root.get("donors") if isinstance(root, dict) else None) or []:
        if isinstance(d, str):
            d = {"name": d}
        if not isinstance(d, dict):
            continue
        name = str(d.get("name") or "").strip()
        if name:
            lst.donors.append({"name": name, "note": d.get("note") or d.get("message"), "date": d.get("date")})
    return lst


